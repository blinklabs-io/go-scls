func TestDRepStateRoundTripAndSetOrder(t *testing.T) {
	t.Parallel()
	value := cardano.DRepState{
		Anchor:  &cardano.Anchor{URL: "https://example.invalid/a", Hash: seq(1, 32)},
		Expiry:  500,
		Deposit: 2_000_000,
		Delegations: []cardano.Credential{
			{Kind: cardano.CredentialScriptHash, Hash: hash28From(9)},
			{Kind: cardano.CredentialKeyHash, Hash: hash28From(7)},
		},
	}
	encoded, err := cardano.EncodeDRepState(value)
	if err != nil {
		t.Fatalf("EncodeDRepState() error = %v", err)
	}
	decoded, err := cardano.DecodeDRepState(encoded)
	if err != nil {
		t.Fatalf("DecodeDRepState() error = %v", err)
	}
	// The set is sorted by encoded bytes: key-hash credential [0, ...] first.
	if decoded.Delegations[0].Kind != cardano.CredentialKeyHash ||
		decoded.Delegations[1].Kind != cardano.CredentialScriptHash {
		t.Fatalf("delegations not in canonical order: %#v", decoded.Delegations)
	}
	again, err := cardano.EncodeDRepState(decoded)
	if err != nil || !bytes.Equal(again, encoded) {
		t.Fatalf("re-encode = %x (%v), want %x", again, err, encoded)
	}

	// Hand-built unsorted set must be rejected.
	unsorted, err := cbor.Marshal(cbor.Map{
		{Key: "anchor", Value: nil},
		{Key: "expiry", Value: uint64(0)},
		{Key: "deposit", Value: uint64(0)},
		{Key: "delegations", Value: cbor.Tag{Number: 258, Value: cbor.Array{
			cbor.Array{uint64(1), seq(0, 28)},
			cbor.Array{uint64(0), seq(0, 28)},
		}}},
	})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := cardano.DecodeDRepState(unsorted); !errors.Is(err, cardano.ErrPayload) {
		t.Fatalf("DecodeDRepState(unsorted set) error = %v, want ErrPayload", err)
	}
	long := cardano.DRepState{Anchor: &cardano.Anchor{URL: string(make([]byte, 129)), Hash: nil}}
	if _, err := cardano.EncodeDRepState(long); !errors.Is(err, cardano.ErrPayload) {
		t.Fatalf("EncodeDRepState(long URL) error = %v, want ErrPayload", err)
	}
}

func TestCommitteeStateCanonicalOrder(t *testing.T) {
	t.Parallel()
	low := cardano.Credential{Kind: cardano.CredentialKeyHash, Hash: hash28From(1)}
	high := cardano.Credential{Kind: cardano.CredentialScriptHash, Hash: hash28From(1)}
	value := cardano.CommitteeState{
		{Cold: high, Authorization: cardano.CommitteeAuthorization{
			Kind: cardano.CommitteeResigned, Anchor: &cardano.Anchor{URL: "u", Hash: []byte{1}},
		}},
		{Cold: low, Authorization: cardano.CommitteeAuthorization{
			Kind: cardano.CommitteeHotCredential, HotCredential: high,
		}},
	}
	encoded, err := cardano.EncodeCommitteeState(value)
	if err != nil {
		t.Fatalf("EncodeCommitteeState() error = %v", err)
	}
	decoded, err := cardano.DecodeCommitteeState(encoded)
	if err != nil {
		t.Fatalf("DecodeCommitteeState() error = %v", err)
	}
	want := cardano.CommitteeState{value[1], value[0]}
	if !reflect.DeepEqual(decoded, want) {
		t.Fatalf("decoded = %#v, want %#v", decoded, want)
	}

	resignedNoAnchor := cardano.CommitteeState{{Cold: low, Authorization: cardano.CommitteeAuthorization{Kind: cardano.CommitteeResigned}}}
	encoded, err = cardano.EncodeCommitteeState(resignedNoAnchor)
	if err != nil {
		t.Fatal(err)
	}
	if got := encoded[len(encoded)-3:]; !bytes.Equal(got, []byte{0x82, 0x01, 0xf6}) {
		t.Fatalf("resignation without anchor ends %x, want 8201f6", got)
	}

	dup := cardano.CommitteeState{value[1], value[1]}
	if _, err := cardano.EncodeCommitteeState(dup); !errors.Is(err, cardano.ErrPayload) {
		t.Fatalf("EncodeCommitteeState(duplicate) error = %v, want ErrPayload", err)
	}

	reversed, err := cbor.Marshal(cbor.Map{})
	if err != nil {
		t.Fatal(err)
	}
	reversed = append([]byte{0xa2}, reversed[:0]...)
	reversed = append(reversed,
		append(append([]byte{0x82, 0x01, 0x58, 0x1c}, h28(1)...), 0x82, 0x01, 0xf6)...)
	reversed = append(reversed,
		append(append([]byte{0x82, 0x00, 0x58, 0x1c}, h28(1)...), 0x82, 0x01, 0xf6)...)
	if _, err := cardano.DecodeCommitteeState(reversed); !errors.Is(err, cbor.ErrMapOrder) {
		t.Fatalf("DecodeCommitteeState(reversed) error = %v, want ErrMapOrder", err)
	}
}

