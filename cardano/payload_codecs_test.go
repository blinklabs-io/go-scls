func TestProtocolParametersRoundTrip(t *testing.T) {
	t.Parallel()
	value := fixtureProtocolParameters()
	value.MinFeeA = 44
	value.MaxTxSize = math.MaxUint32
	value.MaxBlockHeaderSize = math.MaxUint16
	value.ProtocolVersion = cardano.ProtocolVersion{Major: 10, Minor: 2}
	value.A0 = cardano.Rational{Numerator: 3, Denominator: 10}
	value.CostModels = map[uint8][]int64{
		2:   {-1, 0, math.MaxInt64, math.MinInt64},
		0:   {7},
		255: {},
	}
	value.MaxBlockExUnits = cardano.ExUnits{Memory: 1, Steps: math.MaxUint64}
	encoded, err := cardano.EncodeProtocolParameters(value)
	if err != nil {
		t.Fatalf("EncodeProtocolParameters() error = %v", err)
	}
	decoded, err := cardano.DecodeProtocolParameters(encoded)
	if err != nil {
		t.Fatalf("DecodeProtocolParameters() error = %v", err)
	}
	if !reflect.DeepEqual(decoded, value) {
		t.Fatalf("round trip = %#v, want %#v", decoded, value)
	}
	// Cost-model keys are encoded in ascending order regardless of insertion.
	generic, err := cbor.Unmarshal(encoded)
	if err != nil {
		t.Fatal(err)
	}
	for _, entry := range generic.(cbor.Map) {
		if entry.Key != uint64(18) {
			continue
		}
		var keys []uint64
		for _, model := range entry.Value.(cbor.Map) {
			keys = append(keys, model.Key.(uint64))
		}
		if !reflect.DeepEqual(keys, []uint64{0, 2, 255}) {
			t.Fatalf("cost model keys = %v, want [0 2 255]", keys)
		}
	}
}

func TestProtocolParametersRejectsInvalid(t *testing.T) {
	t.Parallel()
	fixture := readFixture(t, "gov_pparams_v0.cbor")
	generic, err := cbor.Unmarshal(fixture)
	if err != nil {
		t.Fatal(err)
	}
	mutate := func(key uint64, value any) []byte {
		source := generic.(cbor.Map)
		result := make(cbor.Map, 0, len(source))
		for _, entry := range source {
			if entry.Key == key {
				entry.Value = value
			}
			result = append(result, entry)
		}
		data, err := cbor.Marshal(result)
		if err != nil {
			t.Fatal(err)
		}
		return data
	}
	drop := func(key uint64) []byte {
		source := generic.(cbor.Map)
		result := make(cbor.Map, 0, len(source))
		for _, entry := range source {
			if entry.Key != key {
				result = append(result, entry)
			}
		}
		data, err := cbor.Marshal(result)
		if err != nil {
			t.Fatal(err)
		}
		return data
	}
	rekey := func(from, to uint64) []byte {
		source := generic.(cbor.Map)
		result := make(cbor.Map, 0, len(source))
		for _, entry := range source {
			if entry.Key == from {
				entry.Key = to
			}
			result = append(result, entry)
		}
		data, err := cbor.Marshal(result)
		if err != nil {
			t.Fatal(err)
		}
		return data
	}
	tests := map[string][]byte{
		"max tx size over u32":      mutate(3, uint64(math.MaxUint32)+1),
		"header size over u16":      mutate(4, uint64(65536)),
		"rho above one":             mutate(10, cbor.Tag{Number: 30, Value: cbor.Array{uint64(2), uint64(1)}}),
		"a0 zero denominator":       mutate(9, cbor.Tag{Number: 30, Value: cbor.Array{uint64(0), uint64(0)}}),
		"a0 untagged":               mutate(9, cbor.Array{uint64(0), uint64(1)}),
		"cost model value overflow": mutate(18, cbor.Map{{Key: uint64(0), Value: cbor.Array{cbor.Negative(math.MaxUint64)}}}),
		"cost model key over 255":   mutate(18, cbor.Map{{Key: uint64(256), Value: cbor.Array{}}}),
		"cost model uint overflow":  mutate(18, cbor.Map{{Key: uint64(0), Value: cbor.Array{uint64(math.MaxInt64) + 1}}}),
		"four pool thresholds":      mutate(25, cbor.Array{}),
		"missing key 33":            drop(33),
		"unexpected key 12 for 11":  rekey(11, 12),
	}
	for name, data := range tests {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			if _, err := cardano.DecodeProtocolParameters(data); !errors.Is(err, cardano.ErrPayload) {
				t.Fatalf("DecodeProtocolParameters() error = %v, want ErrPayload", err)
			}
		})
	}
	if _, err := cardano.DecodeProtocolParameters(fixture); err != nil {
		t.Fatalf("control: unmodified fixture error = %v", err)
	}
}

