func TestScalarPayloads(t *testing.T) {
	t.Parallel()
	encoded, err := cardano.EncodeBlocksMade(math.MaxUint64)
	if err != nil {
		t.Fatal(err)
	}
	decoded, err := cardano.DecodeBlocksMade(encoded)
	if err != nil || decoded != math.MaxUint64 {
		t.Fatalf("blocks round trip = %d (%v)", decoded, err)
	}
	if _, err := cardano.DecodeBlocksMade([]byte{0x20}); !errors.Is(err, cardano.ErrPayload) {
		t.Fatalf("DecodeBlocksMade(-1) error = %v, want ErrPayload", err)
	}
	if _, err := cardano.DecodeBlocksMade([]byte{0x18, 0x00}); !errors.Is(err, cbor.ErrNonMinimal) {
		t.Fatalf("DecodeBlocksMade(non-minimal) error = %v, want ErrNonMinimal", err)
	}
	if _, err := cardano.DecodeVRFKeyHashCount([]byte{0x00}); !errors.Is(err, cardano.ErrPayload) {
		t.Fatalf("DecodeVRFKeyHashCount(0) error = %v, want ErrPayload", err)
	}
	if _, err := cardano.EncodeVRFKeyHashCount(0); !errors.Is(err, cardano.ErrPayload) {
		t.Fatalf("EncodeVRFKeyHashCount(0) error = %v, want ErrPayload", err)
	}
	encoded, err = cardano.EncodeVRFKeyHashCount(math.MaxUint64)
	if err != nil {
		t.Fatal(err)
	}
	count, err := cardano.DecodeVRFKeyHashCount(encoded)
	if err != nil || count != math.MaxUint64 {
		t.Fatalf("vrf round trip = %d (%v)", count, err)
	}
}

