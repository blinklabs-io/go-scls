func seq(start byte, count int) []byte {
	result := make([]byte, count)
	for i := range result {
		result[i] = start + byte(i)
	}
	return result
}

func hash28From(start byte) cardano.Hash28 {
	var result cardano.Hash28
	copy(result[:], seq(start, 28))
	return result
}

func hash32From(start byte) cardano.Hash32 {
	var result cardano.Hash32
	copy(result[:], seq(start, 32))
	return result
}

func ptr[T any](value T) *T {
	return &value
}

func neutralNonces() cardano.Nonces {
	return cardano.Nonces{CertCounters: map[cardano.Hash28]uint64{}}
}

